"""Turn results/results.csv into a short, readable summary of the main results.

    python scripts/summarize_results.py          # writes results/summary.md

All values are percentages. Each (run_id, eval_set, metric) appears once in results.csv;
if an older file still has repeats, the newest row wins.
"""
import argparse
import csv
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CLASSES = ["bird", "cat", "dog", "horse", "sheep", "cow", "elephant", "bear", "zebra", "giraffe"]
# run ids stay as in configs/ and runs/; tables and figures show what each run combines:
# initialisation · which layers train · augmentation
CLASSIFIERS = [("C1_finetune_aug", "ImageNet · all layers · aug"),
               ("C2_finetune_noaug", "ImageNet · all layers · no aug"),
               ("C3_linear_probe", "ImageNet · head only · aug"),
               ("C4_scratch", "Random init · all layers · aug"),
               ("clip_zeroshot", "CLIP zero-shot"),
               ("majority", "Majority class")]
PIPELINE = "D1_agnostic+C1_finetune_aug"
DETECTORS = [("D1_agnostic", "val_agnostic", "test_agnostic", "Detector, animal vs background*"),
             ("D2_10class", "val", "test", "One-stage: detector, 10 classes"),
             (PIPELINE, None, "test", "Two-stage: detector + classifier")]
CORRUPTIONS = [f"{k}{s}" for k in ("lowlight", "blur", "contrast") for s in (1, 2)]
DASH = "–"


def load_latest(path):
    """{(run_id, eval_set, metric): row}; a later row replaces an earlier one."""
    latest = {}
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            latest[(row["run_id"], row["eval_set"], row["metric"])] = row
    return latest


def value(latest, run, eval_set, metric):
    row = latest.get((run, eval_set, metric))
    return float(row["value"]) if row else None


def pct(v):
    return DASH if v is None else f"{100 * v:.1f}"


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    return "\n".join(lines + ["| " + " | ".join(r) + " |" for r in rows])


def build(latest):
    out = ["# Results summary", "",
           "Generated by `scripts/summarize_results.py` from `results/results.csv`. All values in %.", ""]

    out += ["## Classification of ground-truth crops (RQ1)", ""]
    rows = [[name, pct(value(latest, run, "val", "macro_f1")),
             *(pct(value(latest, run, "test", m)) for m in ("accuracy", "macro_precision", "macro_recall", "macro_f1"))]
            for run, name in CLASSIFIERS]
    out += [table(["Model", "Val F1", "Test acc.", "Test prec.", "Test rec.", "Test F1"], rows), "",
            "Precision, recall and F1 are macro-averaged over the 10 classes.", ""]

    out += ["## Test accuracy by object size", ""]
    rows = [[name, *(pct(value(latest, run, "test", f"accuracy_{b}")) for b in ("small", "medium", "large"))]
            for run, name in CLASSIFIERS[:5]]
    out += [table(["Model", "Small (< 32² px)", "Medium", "Large (≥ 96² px)"], rows), "",
            "Train/val crops drop boxes with a short side under 32 px, so no small box was seen in training.", ""]

    out += ["## Detection on full images (RQ2, RQ3)", ""]
    rows = [[name, pct(value(latest, run, val_set, "AP50")) if val_set else DASH,
             *(pct(value(latest, run, test_set, m)) for m in
               ("AP50", "AP", "AP_small", "AP_medium", "AP_large", "multi_recall50", "multi_count_accuracy"))]
            for run, val_set, test_set, name in DETECTORS]
    out += [table(["Method", "Val AP50", "Test AP50", "AP", "AP small", "AP medium", "AP large",
                   "Recall, ≥2 animals", "Count acc., ≥2 animals"], rows), "",
            "*Class-agnostic: any box on an animal counts, so its AP is not comparable with the 10-class rows.", ""]

    out += ["## Two-stage vs. one-stage, per-class test AP50 (RQ3)", ""]
    rows = []
    for c in CLASSES + [None]:
        metric = "AP50" if c is None else f"AP50_{c}"
        one, two = value(latest, "D2_10class", "test", metric), value(latest, PIPELINE, "test", metric)
        delta = DASH if one is None or two is None else f"{100 * (two - one):+.1f}"
        rows.append(["**mean**" if c is None else c, pct(one), pct(two), delta])
    out += [table(["Class", "One-stage", "Two-stage", "Δ"], rows), ""]

    out += ["## Robustness to corruptions, test set (RQ4)", ""]
    sets = ["test"] + [f"test_{c}" for c in CORRUPTIONS]
    rows = [[f"{name} (F1)", *(pct(value(latest, run, s, "macro_f1")) for s in sets)]
            for run, name in (CLASSIFIERS[0], CLASSIFIERS[1], CLASSIFIERS[4])]
    rows.append(["Two-stage (mAP50)", *(pct(value(latest, PIPELINE, s, "AP50")) for s in sets)])
    out += [table(["Model", "Clean", "Low light 1", "Low light 2", "Blur 1", "Blur 2",
                   "Low contrast 1", "Low contrast 2"], rows), ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", default=REPO / "results" / "results.csv")
    ap.add_argument("--out", default=REPO / "results" / "summary.md")
    args = ap.parse_args()
    text = build(load_latest(args.csv))
    Path(args.out).write_text(text)
    print(text)
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    main()
